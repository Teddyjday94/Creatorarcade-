// Turns drizzle/*.sql into db/migrations.generated.ts so the app can apply them
// without reading files at runtime (serverless bundles do not ship loose .sql files).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const files = readdirSync('drizzle').filter((f) => f.endsWith('.sql')).sort();
const entries = files.map((f) => `  { name: ${JSON.stringify(f.replace(/\.sql$/, ''))}, sql: ${JSON.stringify(readFileSync('drizzle/' + f, 'utf8'))} },`);
writeFileSync('db/migrations.generated.ts', `// Generated by scripts/bundle-migrations.mjs. Do not edit; run \`pnpm db:generate\`.\nexport const MIGRATIONS: Array<{ name: string; sql: string }> = [\n${entries.join('\n')}\n];\n`);
console.log('Bundled', files.length, 'migrations');
